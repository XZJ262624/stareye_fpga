"""Generate exact STA pin selectors from the reviewed synthesized M5B1 netlist.

The installed get_pins -regexp accepts exact escaped names but rejects the
grouped/quantified patterns used by Python. Expand them here; each pin must
resolve exactly once in every subsequent placement, routing and STA run.
"""
from pathlib import Path
import re,json,hashlib
R=Path(__file__).resolve().parents[1];W=R/'efinity/m5b1_global_canny_i3';O=R/'reports/m5b1_global_canny_i3'
def main():
 net=W/'outflow/Ti60_Demo.map.v';raw=net.read_bytes();text=raw.decode();names=re.findall(r'EFX_FF \\(\S+)',text);groups={}
 def select(key,pattern,pin,count):
  selected=sorted(n+'|'+pin for n in names if re.fullmatch(pattern,n));assert len(selected)==count,(key,len(selected),count)
  groups[key]=selected;return key
 gray=[]
 for fifo in ('video/camera_fifo','video/display_fifo','background/capture/fifo'):
  for g,b,t in [('rg','rp','rgs1'),('wg','wp','wgs1')]:
   key=fifo.replace('/','_')+'_'+t
   # 9 explicit Gray registers + 10 binary registers, with MSB Gray alias.
   src=select(key+'_source',rf'u_m5b1/{fifo}/({g}|{b})\[\d+\]~FF','CLK',19)
   dst=select(key+'_destination',rf'u_m5b1/{fifo}/{t}\[\d+\]~FF','D',10);gray.append((src,dst))
 mail=[]
 for box,dst,bits in [('video/eof_box','video/eof_count',20),('video/offer_box','video/offer_id',64),('background/capture/arm_box','background/capture/arm_data',65),('background/capture/descriptor_box','background/cap_descriptor',204)]:
  key=box.replace('/','_');src=select(key+'_source',rf'u_m5b1/{box}/held\[\d+\]~FF','CLK',bits);dest=select(key+'_destination',rf'u_m5b1/{dst}\[\d+\]~FF','D',bits);mail.append((src,dest))
 select('toggle_first',r'u_m5b1/(video/(eof_box|consumed_box|offer_box)|background/capture/(arm_box|descriptor_box))/(req_sync|ack_sync)\[0\]~FF','D',10)
 select('status_first',r'u_m5b1/(video/(cam_run|pix_run|cf|pf|camera_over_sync|display_under_sync)\[0\]|background/(dropped_sync\[0\]|capture/(over_sync\[0\]|cancel_meta)))~FF','D',9)
 select('reset_release',r'u_m5b1/(fifo_ready|video/((camera_fifo|display_fifo)/(wrs|rrs)|(eof_box|consumed_box|offer_box)/(srelease|drelease)|crelease|prelease)|background/capture/(fifo/(wrs|rrs)|(arm_box|descriptor_box)/(srelease|drelease)|prelease))\[[0-5]\]~FF','SR',38)
 select('bridge_ready_first',r'u_m5b1/bridge/rs\[0\]~FF','D',1)
 select('camera_reset_release',r'm5b1_cam_reset\[[01]\]~FF','SR',2)
 # Prevent a timing exception from legitimizing an SRL-based synchronizer.
 assert not re.search(r'EFX_SRL8 \\u_m5b1/',text),'M5B1 synchronizer extracted to SRL8'
 for chain in ('ds','ps','fs','rs'):
  assert all(f'u_m5b1/bridge/{chain}[{stage}]~FF' in names for stage in (0,1))
 sdc=W/'Ti60_Demo_I3.sdc';prefix=sdc.read_text().split('# M5B1 explicit CDC endpoints.',1)[0]
 body='''# M5B1 explicit CDC endpoints. Generated by scripts/m5b1_constraints.py.
# Only exact named first-stage CDC endpoints and reset-release SR pins are cut.
# Gray and stable-mailbox paths have 5ns register-launch-to-D setup budgets.
# Efinity names the launch point CLK. Final detailed reports additionally audit
# clock-to-Q plus physical data delay and skew < one fastest 10ns source tick.
proc m5b1_exact {selectors label} {
 set result {}
 foreach selector $selectors {
  set one [get_pins -regexp $selector]
  if {[llength $one] != 1} {error "M5B1 exact CDC selector $label / $selector did not resolve once"}
  set result [concat $result $one]
 }
 puts "M5B1_CDC_PINS $label [llength $result] $result"
 return $result
}
'''
 for key,pins in groups.items():
  body+=f'set m5b1_{key} [m5b1_exact {{\n'
  for pin in pins:body+=' {'+'^'+re.escape(pin)+'$'+'}\n'
  body+='} '+key+']\n'
 for src,dst in gray+mail:
  body+=f'set_max_delay -from $m5b1_{src} -to $m5b1_{dst} 5.0\nset_false_path -hold -from $m5b1_{src} -to $m5b1_{dst}\n'
 for key in ('toggle_first','status_first','reset_release','bridge_ready_first','camera_reset_release'):body+=f'set_false_path -to $m5b1_{key}\n'
 generated=prefix+body
 if sdc.read_text()!=generated:sdc.write_text(generated)
 manifest=dict(map_sha256=hashlib.sha256(raw).hexdigest(),map_bytes=len(raw),sdc_sha256=hashlib.sha256(sdc.read_bytes()).hexdigest(),groups=groups,gray_pairs=gray,mailbox_pairs=mail,policy='5ns launch CLK-to-D max; hold only exception for asynchronous Gray/mailbox; exact first-stage control D and explicit reset-release SR exceptions')
 (O/'CDC_PIN_MANIFEST.json').write_text(json.dumps(manifest,indent=2));print('M5B1_CDC_EXACT_SELECTORS',len(groups),sum(map(len,groups.values())))
if __name__=='__main__':main()
